#!/usr/bin/env python3
"""Turn Figma-exported icon SVGs (Lucide set) into Borro/Components/IconData.swift.

Usage: python3 tools/gen_icons.py <svg-dir>
Figma exports absolute M/L/H/V/C/Z paths, which Icon.swift parses at runtime.
"""
import os, re, sys
import xml.etree.ElementTree as ET

NS = "{http://www.w3.org/2000/svg}"
SKIP = {"battery", "cellular-signal", "signal", "wi-fi"}  # fake status bar: we use the real one

def camel(name):
    parts = re.split(r"[-_ ]+", name)
    s = parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])
    return {"back": "back", "default": "defaultIcon"}.get(s, s)

def rect_path(e):
    x, y = float(e.get("x", 0)), float(e.get("y", 0))
    w, h = float(e.get("width")), float(e.get("height"))
    r = min(float(e.get("rx", 0)), w / 2, h / 2)
    k = 0.5523 * r
    if r == 0:
        return f"M{x} {y}H{x+w}V{y+h}H{x}Z"
    return (f"M{x+r} {y}H{x+w-r}C{x+w-r+k} {y} {x+w} {y+r-k} {x+w} {y+r}V{y+h-r}"
            f"C{x+w} {y+h-r+k} {x+w-r+k} {y+h} {x+w-r} {y+h}H{x+r}C{x+r-k} {y+h} {x} {y+h-r+k} {x} {y+h-r}"
            f"V{y+r}C{x} {y+r-k} {x+r-k} {y} {x+r} {y}Z")

def main(src):
    out = ["// Generated by tools/gen_icons.py from Figma SVG exports (Lucide icons, ISC licence). Do not edit.", "",
           "import CoreGraphics", "", "extension Icon {", "    var data: IconData {", "        switch self {"]
    cases = []
    for fn in sorted(os.listdir(src)):
        name = fn[:-4]
        if not fn.endswith(".svg") or name in SKIP: continue
        root = ET.parse(os.path.join(src, fn)).getroot()
        vb = [float(v) for v in root.get("viewBox").split()]
        parts = []
        for e in root.iter():
            tag = e.tag.replace(NS, "")
            if tag not in ("path", "rect"): continue
            if any(p.tag.replace(NS, "") in ("clipPath", "defs") for p in root.iter() if e in list(p)):
                continue
            d = e.get("d") if tag == "path" else rect_path(e)
            if e.get("stroke"):
                parts.append(f'.init(d: "{d}", style: .stroke({e.get("stroke-width", "1")}))')
            elif (e.get("fill") or "").lower() in ("white", "#ffffff"):
                parts.append(f'.init(d: "{d}", style: .knockout)')
            elif e.get("fill") and e.get("fill") != "none":
                parts.append(f'.init(d: "{d}", style: .fill)')
        if not parts: continue
        case = camel(name)
        cases.append(case)
        out.append(f"        case .{case}: return IconData(size: CGSize(width: {vb[2]:g}, height: {vb[3]:g}), parts: [")
        out += [f"            {p}," for p in parts]
        out.append("        ])")
    out += ["        }", "    }", "}", "", "enum Icon: String, CaseIterable {"]
    out += [f"    case {c}" for c in cases]
    out += ["}", ""]
    open("Borro/Components/IconData.swift", "w").write("\n".join(out))
    print(len(cases), "icons:", " ".join(cases))

if __name__ == "__main__":
    main(sys.argv[1])
