#!/usr/bin/env python3
"""Generate Borro/Core/Screen.swift (one case per Figma Prototype frame) from Docs/figma-links.json.

Run after re-dumping links: python3 tools/gen_screens.py
"""
import json, re

TABS = {
    "home": "1.1 1.2 1.3 1.4 1.5 11.4",
    "you": "8.9",
    "lend": "3.2 3.3 3.4 3.6 3.7 3.5 4.11 4.13 5.1 6.1 6.2 6.6 6.7 6.8 6.9 6.10 6.3 6.4 6.5 7.2 7.3 7.4 7.5 8.6 8.7 "
            "9.1 9.2 9.3 9.4 9.5 9.6 9.7 9.8 9.9 9.10 9.11 9.12 9.13 9.14 9.15 9.16 9.17 6.3a 6.3b 6.5a 6.6a 7.2a 7.2b 7.2c 7.2d",
}
NO_TAB = set("3.1 3.8 4.12 8.1 8.5 10.10 11.2".split())
# Sheet heights in pt, measured from the Figma frame (852 minus the sheet's top edge).
SHEETS = {"1.4": 767, "2.2": 531, "4.2": 640, "4.3": 600, "4.4": 640, "4.5": 600, "4.6": 644, "4.10": 278,
          "4.12": 414, "5.2a": 295, "5.3": 335, "5.4": 227, "6.2": 374, "6.3": 387, "6.3a": 387, "6.3b": 387,
          "6.8": 387, "6.9": 387, "6.13": 393, "6.17": 375, "6.18": 396, "7.4": 396, "9.2": 477, "9.4": 433,
          "9.5": 377, "9.6": 271, "11.1": 511, "11.2": 511}
OVERLAYS = {"1.3", "3.7", "6.7", "6.16", "9.7"}
PUSHES = {"3.1", "3.8", "8.1", "8.5", "10.10"}

def camel(title):
    title = re.sub(r"\(.*?\)", lambda m: " " + m.group(0)[1:-1], title)
    words = re.findall(r"[A-Za-z0-9]+", title.replace("’", "").replace("'", ""))
    return "".join(w[:1].upper() + w[1:] for w in words)

d = json.load(open("Docs/figma-links.json"))
def key(s):
    m = re.match(r"(\d+)\.(\d+)([a-z]?)", s["code"])
    return (int(m.group(1)), int(m.group(2)), m.group(3))
screens = sorted(d["screens"], key=key)
cases, rows = [], []
for s in screens:
    code = s["code"]
    case = "s" + code.replace(".", "_")
    who, _, title = s["name"].split(" ", 1)[1].partition(" · ")
    role = {"James": ".james", "Thomas": ".thomas"}.get(who, ".both")
    tab = "nil" if code in NO_TAB or code in SHEETS or code in OVERLAYS else \
        next((f".{t}" for t, codes in TABS.items() if code in codes.split()), ".borro")
    pres = f".sheet(height: {SHEETS[code]})" if code in SHEETS else ".overlay" if code in OVERLAYS else \
        ".push" if code in PUSHES else ".page"
    view = f"S{code.replace('.', '_')}_{camel(title)}View"
    cases.append(f"    case {case}")
    rows.append((case, code, s["name"], s["id"], role, tab, pres, view))

out = ["// Generated by tools/gen_screens.py from Docs/figma-links.json. Do not edit by hand.", "",
       "import SwiftUI", "", "/// One case per frame on the Figma Prototype page.",
       "enum Screen: String, CaseIterable, Hashable, Identifiable {"] + cases + [
       "", "    var id: String { rawValue }", ""]
def prop(name, typ, idx):
    lines = [f"    var {name}: {typ} {{", "        switch self {"]
    for r in rows:
        v = r[idx]
        if typ == "String": v = json.dumps(v, ensure_ascii=False)
        lines.append(f"        case .{r[0]}: return {v}")
    lines += ["        }", "    }", ""]
    return lines
out += prop("code", "String", 1) + prop("frameName", "String", 2) + prop("nodeId", "String", 3)
out += prop("role", "Role", 4) + prop("tab", "AppTab?", 5) + prop("presentation", "Presentation", 6)
out += ["    @MainActor @ViewBuilder", "    var view: some View {", "        switch self {"]
out += [f"        case .{r[0]}: {r[7]}()" for r in rows]
out += ["        }", "    }", "}", ""]
open("Borro/Core/Screen.swift", "w").write("\n".join(out))
json.dump([[r[0], r[1], r[7], r[3], r[2]] for r in rows], open("/tmp/borro-views.json", "w"), ensure_ascii=False)
print(len(rows), "screens")
